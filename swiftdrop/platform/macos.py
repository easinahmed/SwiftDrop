"""macOS integration via PyObjC (no shell commands built from user input).

* Finder reveal / open with the default app: ``NSWorkspace``
* Clipboard: ``NSPasteboard`` (respects "concealed"/"transient" markers set by
  password managers; contents are never logged or stored)
* Notifications: ``UNUserNotificationCenter`` inside the signed .app bundle;
  outside a bundle (development) they are written to the log instead
* Short on-screen messages: a borderless, non-activating ``NSPanel`` that fades away
* Open at login: ``SMAppService`` (macOS 13+, installed app only)
"""

from __future__ import annotations

import threading
import uuid
from collections.abc import Callable
from pathlib import Path
from typing import Any

from swiftdrop.logging_setup import get_logger
from swiftdrop.paths import is_frozen

log = get_logger("macos")

try:  # PyObjC is a hard dependency of the app, but keep imports soft for tooling.
    import AppKit
    import Foundation
    from PyObjCTools import AppHelper
except ImportError:  # pragma: no cover - only on non-macOS tooling environments
    AppKit = None
    Foundation = None
    AppHelper = None

_CONCEALED_TYPES = frozenset(
    {
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    }
)
MAX_CLIPBOARD_CHARS = 200_000
FLASH_SECONDS = 1.8


def run_on_main(fn: Callable[[], Any], timeout: float = 3.0) -> Any:
    """Run ``fn`` on the AppKit main thread and return its result."""
    if threading.current_thread() is threading.main_thread() or AppKit is None:
        return fn()
    app = AppKit.NSApp()
    if app is None or not app.isRunning():
        return fn()
    done = threading.Event()
    box: dict[str, Any] = {}

    def call() -> None:
        try:
            box["value"] = fn()
        except Exception as exc:  # pragma: no cover - surfaced to caller
            box["error"] = exc
        finally:
            done.set()

    AppHelper.callAfter(call)
    if not done.wait(timeout):
        raise TimeoutError("main thread busy")
    if "error" in box:
        raise box["error"]
    return box.get("value")


class MacPlatform:
    def __init__(self) -> None:
        self._monitor_thread: threading.Thread | None = None
        self._monitor_stop = threading.Event()
        self._notification_center: Any = None
        self._notification_delegate: Any = None
        self._notifications_ready = False
        self._notifications_allowed = False
        self._flash_panels: list[Any] = []  # kept alive until they close

    # -- Finder -----------------------------------------------------------
    def reveal(self, path: Path) -> bool:
        workspace = AppKit.NSWorkspace.sharedWorkspace()
        if path.exists():
            url = Foundation.NSURL.fileURLWithPath_(str(path))
            workspace.activateFileViewerSelectingURLs_([url])
            return True
        if path.parent.exists():
            return bool(workspace.openURL_(Foundation.NSURL.fileURLWithPath_(str(path.parent))))
        return False

    def open_path(self, path: Path) -> bool:
        if not path.exists():
            return False
        workspace = AppKit.NSWorkspace.sharedWorkspace()
        return bool(workspace.openURL_(Foundation.NSURL.fileURLWithPath_(str(path))))

    # -- Clipboard --------------------------------------------------------
    def _read_clipboard_main(self) -> str | None:
        board = AppKit.NSPasteboard.generalPasteboard()
        types = {str(t) for t in (board.types() or [])}
        if types & _CONCEALED_TYPES:
            return None
        text = board.stringForType_(AppKit.NSPasteboardTypeString)
        if text is None:
            return None
        text = str(text)
        return text[:MAX_CLIPBOARD_CHARS]

    def read_clipboard(self) -> str | None:
        return run_on_main(self._read_clipboard_main)

    def write_clipboard(self, text: str) -> bool:
        def write() -> bool:
            board = AppKit.NSPasteboard.generalPasteboard()
            board.clearContents()
            return bool(board.setString_forType_(text, AppKit.NSPasteboardTypeString))

        return bool(run_on_main(write))

    def _change_count(self) -> int:
        return int(run_on_main(lambda: AppKit.NSPasteboard.generalPasteboard().changeCount()))

    def _app_in_front(self) -> bool:
        """True while SwiftDrop is the active app (copies made in the app)."""

        def active() -> bool:
            app = AppKit.NSApp()
            return bool(app is not None and app.isActive())

        return bool(run_on_main(active))

    def start_clipboard_monitor(self, callback: Callable[[str], None]) -> None:
        if self._monitor_thread and self._monitor_thread.is_alive():
            return
        self._monitor_stop.clear()

        def loop() -> None:
            try:
                last = self._change_count()
            except Exception:
                last = -1
            while not self._monitor_stop.wait(1.0):
                try:
                    count = self._change_count()
                    if count == last:
                        continue
                    last = count
                    if self._app_in_front():
                        continue  # copied inside SwiftDrop (Copy link, ⌘C): never offer it back
                    text = self.read_clipboard()
                except Exception:
                    log.debug("Clipboard poll failed", exc_info=True)
                    continue
                if text:
                    try:
                        callback(text)
                    except Exception:
                        log.exception("Clipboard callback failed")

        self._monitor_thread = threading.Thread(target=loop, name="clipboard-monitor", daemon=True)
        self._monitor_thread.start()
        log.info("Clipboard monitoring started")

    def stop_clipboard_monitor(self) -> None:
        if self._monitor_thread is None:
            return
        self._monitor_stop.set()
        self._monitor_thread = None
        log.info("Clipboard monitoring stopped")

    # -- Notifications ----------------------------------------------------
    def _ensure_notifications(self) -> bool:
        if self._notifications_ready:
            return self._notification_center is not None
        self._notifications_ready = True
        if not is_frozen():
            return False  # UNUserNotificationCenter requires an app bundle identifier
        try:
            import objc
            import UserNotifications as UN

            center = UN.UNUserNotificationCenter.currentNotificationCenter()

            class _Delegate(Foundation.NSObject):
                def userNotificationCenter_willPresentNotification_withCompletionHandler_(
                    self, _center, _notification, handler
                ):
                    options = getattr(UN, "UNNotificationPresentationOptionBanner", 1 << 4) | getattr(
                        UN, "UNNotificationPresentationOptionList", 1 << 3
                    )
                    handler(options)

            delegate = _Delegate.alloc().init()
            center.setDelegate_(delegate)
            options = UN.UNAuthorizationOptionAlert | UN.UNAuthorizationOptionSound

            def on_auth(granted: bool, error: Any) -> None:
                self._notifications_allowed = bool(granted)
                log.info("Notification permission granted=%s", bool(granted))

            center.requestAuthorizationWithOptions_completionHandler_(options, on_auth)
            self._notification_center = center
            self._notification_delegate = delegate
            del objc
            return True
        except Exception:
            log.warning("Notifications unavailable", exc_info=True)
            return False

    def notify(self, title: str, body: str) -> None:
        if not self._ensure_notifications():
            log.info("Notification: %s — %s", title, body)
            return
        try:
            import UserNotifications as UN

            content = UN.UNMutableNotificationContent.alloc().init()
            content.setTitle_(title[:200])
            content.setBody_(body[:500])
            request = UN.UNNotificationRequest.requestWithIdentifier_content_trigger_(uuid.uuid4().hex, content, None)
            self._notification_center.addNotificationRequest_withCompletionHandler_(request, None)
        except Exception:
            log.warning("Could not post notification", exc_info=True)

    def can_notify(self) -> bool:
        return self._ensure_notifications() and self._notifications_allowed

    def flash_message(self, text: str) -> None:
        def show() -> None:
            panel = _flash_panel(text)
            self._flash_panels.append(panel)
            panel.orderFrontRegardless()

            def close() -> None:
                panel.orderOut_(None)
                if panel in self._flash_panels:
                    self._flash_panels.remove(panel)

            AppHelper.callLater(FLASH_SECONDS, close)

        if AppKit is None:
            return
        try:
            if threading.current_thread() is threading.main_thread():
                show()
            else:
                AppHelper.callAfter(show)
        except Exception:
            log.warning("Could not show a message", exc_info=True)

    # -- Login item -------------------------------------------------------
    def login_item_supported(self) -> bool:
        if not is_frozen():
            return False
        try:
            from ServiceManagement import SMAppService  # noqa: F401
        except ImportError:
            return False
        return True

    def set_login_item(self, enabled: bool) -> None:
        if not self.login_item_supported():
            raise RuntimeError("Open at login is available in the installed app on macOS 13 or later.")
        from ServiceManagement import SMAppService

        service = SMAppService.mainAppService()
        if enabled:
            ok, error = service.registerAndReturnError_(None)
        else:
            ok, error = service.unregisterAndReturnError_(None)
        if not ok:
            raise RuntimeError(f"macOS refused to update the login item: {error}")

    # -- Appearance -------------------------------------------------------
    def set_appearance(self, theme: str) -> None:
        def apply() -> None:
            app = AppKit.NSApp()
            if app is None:
                return
            if theme == "dark":
                app.setAppearance_(AppKit.NSAppearance.appearanceNamed_(AppKit.NSAppearanceNameDarkAqua))
            elif theme == "light":
                app.setAppearance_(AppKit.NSAppearance.appearanceNamed_(AppKit.NSAppearanceNameAqua))
            else:
                app.setAppearance_(None)

        try:
            run_on_main(apply)
        except Exception:
            log.debug("Could not set appearance", exc_info=True)


def _flash_panel(text: str) -> Any:
    """A small HUD near the top of the screen in use; it ignores the mouse and never takes focus."""
    label = AppKit.NSTextField.labelWithString_(text)
    label.setFont_(AppKit.NSFont.systemFontOfSize_weight_(14, AppKit.NSFontWeightMedium))
    label.setTextColor_(AppKit.NSColor.labelColor())
    label.sizeToFit()
    text_size = label.frame().size
    width, height = max(220.0, text_size.width + 48), 46.0
    screen = AppKit.NSScreen.mainScreen() or AppKit.NSScreen.screens()[0]
    visible = screen.visibleFrame()
    x = visible.origin.x + (visible.size.width - width) / 2
    y = visible.origin.y + visible.size.height - height - 64
    style = AppKit.NSWindowStyleMaskBorderless | AppKit.NSWindowStyleMaskNonactivatingPanel
    panel = AppKit.NSPanel.alloc().initWithContentRect_styleMask_backing_defer_(
        Foundation.NSMakeRect(x, y, width, height), style, AppKit.NSBackingStoreBuffered, False
    )
    panel.setReleasedWhenClosed_(False)
    panel.setLevel_(AppKit.NSStatusWindowLevel)
    panel.setOpaque_(False)
    panel.setBackgroundColor_(AppKit.NSColor.clearColor())
    panel.setHasShadow_(True)
    panel.setIgnoresMouseEvents_(True)
    panel.setHidesOnDeactivate_(False)
    panel.setCollectionBehavior_(
        AppKit.NSWindowCollectionBehaviorCanJoinAllSpaces | AppKit.NSWindowCollectionBehaviorFullScreenAuxiliary
    )
    background = AppKit.NSVisualEffectView.alloc().initWithFrame_(Foundation.NSMakeRect(0, 0, width, height))
    background.setMaterial_(AppKit.NSVisualEffectMaterialHUDWindow)
    background.setBlendingMode_(AppKit.NSVisualEffectBlendingModeBehindWindow)
    background.setState_(AppKit.NSVisualEffectStateActive)
    background.setWantsLayer_(True)
    background.layer().setCornerRadius_(12.0)
    background.layer().setMasksToBounds_(True)
    label.setFrameOrigin_(((width - text_size.width) / 2, (height - text_size.height) / 2))
    background.addSubview_(label)
    panel.setContentView_(background)
    return panel


def system_prefers_dark() -> bool:
    if Foundation is None:
        return False
    try:
        style = Foundation.NSUserDefaults.standardUserDefaults().stringForKey_("AppleInterfaceStyle")
        return str(style or "").lower() == "dark"
    except Exception:
        return False
